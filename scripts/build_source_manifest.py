"""Write data/corpus/README.md: the source manifest, generated from data/corpus/sources.json.

Usage: python scripts/build_source_manifest.py
"""
import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = json.loads((ROOT / "data/corpus/sources.json").read_text())
REVIEWS = ROOT / "data/reviews/groww_reviews.csv"
OUT = ROOT / "data/corpus/README.md"
PLAY_URL = "https://play.google.com/store/apps/details?id=com.nextbillion.groww&hl=en_IN"
ORDER = ["Groww", "HDFC Mutual Fund", "SEBI", "AMFI"]


def esc(s: str) -> str:
    return s.replace("|", "\\|")


rows = list(csv.DictReader(open(REVIEWS, encoding="utf-8")))
dates = sorted(r["review_date"] for r in rows)
by_pub = Counter(s["publisher"] for s in SOURCES)
fetched = sorted({s["fetched_at"] for s in SOURCES})

L = []
w = L.append
w("# Source Manifest")
w("")
w(f"Every official URL the system uses: **{len(SOURCES)} official pages** in the answer corpus, plus **1 review source** "
  f"(Google Play), so **{len(SOURCES) + 1} URLs** in total. The brief asks for a corpus of 15–25 official public pages "
  "(AMC, SEBI, AMFI, and official Groww pages for Groww-specific facts). No blogs, private app screens or model memory are used as evidence.")
w("")
w("| Publisher | Pages |")
w("|---|---|")
for p in ORDER:
    w(f"| {p} | {by_pub[p]} |")
w(f"| **Total official pages** | **{len(SOURCES)}** |")
w("| Google Play (reviews) | 1 |")
w("")
w(f"- **Fetched:** {', '.join(fetched)}. Each page's text is stored in [`docs/`](docs) with its sha256 in "
  "[`sources.json`](sources.json). The input list is [`source_list.json`](source_list.json) and the builder is "
  "[`scripts/build_corpus.py`](../../scripts/build_corpus.py).")
w("- **Citations:** each sentence has a stable ID (`<source-id>#s<n>`), and replies can cite only those IDs, "
  "so nothing outside this list can be cited.")
w("- **AMC and schemes:** HDFC Mutual Fund. Flexi Cap, Mid Cap, Small Cap and Nifty 50 Index.")
w("")
w("## Official corpus URLs")
w("")
w("| # | Publisher | Title | URL | Topics | Type | Source ID |")
w("|---|---|---|---|---|---|---|")
n = 0
for p in ORDER:
    for s in [x for x in SOURCES if x["publisher"] == p]:
        n += 1
        w(f"| {n} | {p} | {esc(s['title'])} | <{s['url']}> | {', '.join(s['topics'])} | {s['type']} | `{s['id']}` |")
w("")
w("## Review source")
w("")
w("| # | Source | URL | What was collected |")
w("|---|---|---|---|")
w(f"| {n + 1} | Google Play: Groww app (`com.nextbillion.groww`) | <{PLAY_URL}> | "
  f"{len(rows):,} real public reviews, {dates[0]} → {dates[-1]}, collected by "
  f"[`scripts/collect_reviews.py`](../../scripts/collect_reviews.py) into "
  f"[`data/reviews/groww_reviews.csv`](../reviews/groww_reviews.csv). PII removed before saving and no author names kept. "
  "Each row keeps its own review URL (`&reviewId=…`) and a stable review ID (`GP-…`). |")
w("")
w("## Plain-text URL list")
w("")
w("```")
for p in ORDER:
    for s in [x for x in SOURCES if x["publisher"] == p]:
        w(s["url"])
w(PLAY_URL)
w("```")
w("")
w("*Generated by [`scripts/build_source_manifest.py`](../../scripts/build_source_manifest.py) from `sources.json`.*")
w("")
OUT.write_text("\n".join(L), encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(SOURCES)} official + 1 review source")
